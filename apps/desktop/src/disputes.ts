// ---------------------------------------------------------------------------
// Dispute envelope (AD-6): the small, tagged message a buyer reveals in the
// dispute room. It carries the order id, the complaint, and the buyer's
// dispute SECRET. Revealing the secret -- whose poseidon2 commitment the buyer
// already published on-chain via dispute_order (which only the buyer can call)
// -- is what authenticates them. It replaces the old ~15KB UltraHonk proof:
// a few hundred bytes, delivered in a single message, verified automatically
// by one hash, with no copy-paste.
// ---------------------------------------------------------------------------

export const DISPUTE_ENVELOPE_TAG = 'aztec-market/dispute/v2';

export interface DisputeEnvelope {
  tag: typeof DISPUTE_ENVELOPE_TAG;
  marketplaceAddress: string;
  orderId: string;
  statement: string;
  /** The buyer's dispute secret (hex); revealing it IS the authentication. */
  secret: string;
}

export function serializeDisputeEnvelope(envelope: DisputeEnvelope): string {
  if (envelope.tag !== DISPUTE_ENVELOPE_TAG) {
    throw new Error('refusing to serialize a dispute envelope with the wrong tag');
  }
  return JSON.stringify(envelope);
}

/**
 * Parses a message body as a dispute envelope, or null if it is ordinary chat.
 * Throws only on a body that claims the tag but is malformed.
 */
export function parseDisputeEnvelope(body: string): DisputeEnvelope | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(body);
  } catch {
    return null;
  }
  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    (parsed as { tag?: unknown }).tag !== DISPUTE_ENVELOPE_TAG
  ) {
    return null;
  }
  const e = parsed as Record<string, unknown>;
  if (
    typeof e.marketplaceAddress !== 'string' ||
    typeof e.orderId !== 'string' ||
    typeof e.statement !== 'string' ||
    typeof e.secret !== 'string'
  ) {
    throw new Error('malformed dispute envelope');
  }
  return {
    tag: DISPUTE_ENVELOPE_TAG,
    marketplaceAddress: e.marketplaceAddress,
    orderId: e.orderId,
    statement: e.statement,
    secret: e.secret,
  };
}

/**
 * A friendly summary of a dispute-envelope message, for rendering it in a
 * thread as a readable card instead of raw JSON. Null for ordinary messages.
 */
export function summarizeDisputeEnvelope(
  body: string,
): { orderId: string; statement: string } | null {
  let envelope: DisputeEnvelope | null;
  try {
    envelope = parseDisputeEnvelope(body);
  } catch {
    return null;
  }
  return envelope === null ? null : { orderId: envelope.orderId, statement: envelope.statement };
}

