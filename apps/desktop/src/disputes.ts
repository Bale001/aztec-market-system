// Owner: publish the dispute-intake address
// ---------------------------------------------------------------------------

const DISPUTE_WELCOME =
  'This is the dispute channel for a hidden market. Send the dispute package generated by ' +
  'your marketplace app; a moderator will review it.';

/**
 * Owner action: create (or reuse) the market's SimpleX business address and
 * attest it on-chain under the owner identity, so buyers can find it. Returns
 * the address link.
 */
export async function publishDisputeIntake(
  session: TransactionalSession,
  market: ResolvedMarketplace,
  accessSecret: Fr,
): Promise<string> {
  const marketAddr = market.marketplaceAddress.toString();
  const link = await ensureDisputeAddress(marketAddr, 'Market operator', DISPUTE_WELCOME);
  await setContactAddress({
    wallet: session.wallet,
    node: session.node,
    from: session.from,
    ...marketAction(session),
    marketplaceAddress: market.marketplaceAddress,
    accessSecret,
    simplexAddress: link,
  });
  return link;
}

/** Resolves the market's dispute-intake address (published by the owner). */
export async function resolveDisputeIntake(
  viewer: Session,
  market: ResolvedMarketplace,
  accessSecret: Fr,
): Promise<string | null> {
  const common = {
    wallet: viewer.wallet,
    node: viewer.node,
    from: viewer.from,
    marketplaceAddress: market.marketplaceAddress,
  };
  const superadminIdentity = await getSuperadminIdentity(common);
  return getContactAddress({ ...common, identity: superadminIdentity, accessSecret });
}

